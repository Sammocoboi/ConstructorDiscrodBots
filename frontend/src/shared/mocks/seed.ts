const moduleState = (bot: Bot, module: ModuleManifest): ModuleState => {
  const enabledByBot: Record<string, string[]> = {
    bot_community: ['greetings', 'moderation', 'roles', 'logs', 'polls'],
    bot_moderator: ['moderation', 'logs', 'tickets', 'roles'],
    bot_events: ['greetings', 'polls', 'economy'],
  }
  const settings: Record<string, Record<string, unknown>> = {}
  for (const guild of bot.guilds) {
    const defaults = schemaDefaults(module.settingsSchema)
    const guildDefaults: Record<string, unknown> = {
      channelId: findChannel(guild, 'welcome') || findChannel(guild, 'general'),
      logChannelId: findChannel(guild, 'logs') || findChannel(guild, 'general'),
      levelUpChannelId: findChannel(guild, 'general'),
      reactionRoleChannelId: findChannel(guild, 'rules') || findChannel(guild, 'general'),
      categoryId: guild.channels.find((channel) => channel.type === 'category')?.id ?? '',
      autoRoleId: guild.roles.find((role) => role.id === 'role_member')?.id ?? '',
      verificationRoleId: guild.roles.find((role) => role.id === 'role_member')?.id ?? '',
      supportRoleId: guild.roles.find((role) => role.id === 'role_mod')?.id ?? '',
    }
    settings[guild.id] = { ...defaults, ...guildDefaults }
  }
  return {
    botId: bot.id,
    moduleId: module.id,
    enabled: enabledByBot[bot.id]?.includes(module.id) ?? module.enabledByDefault,
    settings,
    warnings:
      bot.id === 'bot_events' && module.id === 'moderation'
        ? ['Роль бота ниже роли «Модератор» — тайм-ауты не сработают.']
        : [],
    updatedAt: ago(day * 3),
  }
}

